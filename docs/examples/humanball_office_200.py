class S:
    def __init__(self):
        self.im=Image.new('RGBA',(18,18)); self.d=ImageDraw.Draw(self.im)
    def r(self,box,c): self.d.rectangle(box,fill=c); return self
    def p(self,points,c): self.d.polygon(points,fill=c); return self
    def l(self,points,c,w=1): self.d.line(points,fill=c,width=w); return self
    def e(self,box,c): self.d.ellipse(box,fill=c); return self
    def dot(self,x,y,c): self.d.point((x,y),fill=c); return self
    def clear(self,box): self.d.rectangle(box,fill=(0,0,0,0)); return self

