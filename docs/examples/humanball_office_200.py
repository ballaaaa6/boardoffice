def render(root):
    root.mkdir(parents=True,exist_ok=True)
    fontpath=Path('C:/Windows/Fonts/tahoma.ttf')
    font=ImageFont.truetype(str(fontpath),17) if fontpath.exists() else ImageFont.load_default()
    heading=ImageFont.truetype(str(fontpath),24) if fontpath.exists() else font
    manifest={'cell':[18,18],'border':{'black':K,'cream':C,'width':1},'categories':[]}
    seen={}; audits=[]; overviews=[]
    for cat in CAT:
        assert len(cat['items'])==20,(cat['id'],len(cat['items']))
        dest=root/cat['id']; dest.mkdir(exist_ok=True)
        sheet=Image.new('RGBA',(90,72));review=Image.new('RGB',(1040,960),'#252830');rd=ImageDraw.Draw(review)
        rd.text((22,12),cat['title'],font=heading,fill='#EEE8D8')
        cm={'id':cat['id'],'title':cat['title'],'items':[]}
        for i,(id,label,fill) in enumerate(cat['items']):
            f={(x,y) for y in range(18) for x in range(18) if fill.getpixel((x,y))[3]}
            dil=lambda pts:{(x+a,y+b) for x,y in pts for a in (-1,0,1) for b in (-1,0,1)}
            b=dil(f)-f;c=dil(f|b)-f-b
            assert f and all(0<=x<18 and 0<=y<18 for x,y in f|b|c),(cat['id'],id,'clipped fill/border')
            out=Image.new('RGBA',(18,18));od=ImageDraw.Draw(out)
            for pts,col in [(c,C),(b,K)]:
                for pt in pts:od.point(pt,fill=col)
            out.alpha_composite(fill)
            out.save(dest/(id+'.png'))
            actual=Image.open(dest/(id+'.png')).convert('RGBA')
            assert actual.size==(18,18) and set(actual.getchannel('A').getdata())<={0,255}
            assert actual.tobytes()==out.tobytes()
            for pts,col in [(b,K),(c,C)]:
                rgba=Image.new('RGBA',(1,1),col).getpixel((0,0)); assert all(actual.getpixel(pt)==rgba for pt in pts)
            digest=hashlib.sha256(actual.tobytes()).hexdigest()
            assert digest not in seen,(id,'duplicate artwork',seen.get(digest))
            seen[digest]=cat['id']+'/'+id
            row=i//5; col=i%5;sheet.alpha_composite(out,(col*18,row*18))
            large=out.resize((180,180),Image.Resampling.NEAREST);review.paste(large,(22+col*204,53+row*223),large)
            text=f'{i+1:02} {label}'
            usefont=font
            if rd.textlength(text,font=font)>196 and fontpath.exists(): usefont=ImageFont.truetype(str(fontpath),14)
            rd.text((22+col*204,235+row*223),text,font=usefont,fill='#EEE8D8')
            cm['items'].append({'index':i+1,'id':id,'label':label,'row':row+1,'column':col+1,'sha256_rgba':digest})
            audits.append({'category':cat['id'],'id':id,'size_ok':True,'alpha_binary':True,'complete_unclipped_rings':True})
        sheet.save(dest/'sheet_native.png'); sheet.resize((900,720),Image.Resampling.NEAREST).save(dest/'sheet_10x.png');review.save(dest/'sheet_review.png')
        saved=Image.open(dest/'sheet_native.png').convert('RGBA')
        for i,(id,_,_) in enumerate(cat['items']):
            x=(i%5)*18;y=(i//5)*18
            cell=saved.crop((x,y,x+18,y+18)); individual=Image.open(dest/(id+'.png')).convert('RGBA')
            assert cell.tobytes()==individual.tobytes(),(cat['id'],id,[(j,a,b) for j,(a,b) in enumerate(zip(cell.getdata(),individual.getdata())) if a!=b][:4])
        (dest/'manifest.json').write_text(json.dumps(cm,ensure_ascii=False,indent=2),encoding='utf-8')
        manifest['categories'].append(cm);overviews.append((cat['title'],sheet))
    manifest['total']=len(audits)
    (root/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
    (root/'audit.json').write_text(json.dumps({'total':len(audits),'unique':len(seen),'exact_sheet_cells':True,'items':audits},indent=2),encoding='utf-8')
    overview=Image.new('RGB',(1040,450*5),'#252830');ovd=ImageDraw.Draw(overview)
